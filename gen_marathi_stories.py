os.makedirs("app/src/main/res/raw", exist_ok=True)

for filename, inputs in stories:
    data = {
        "inputs": inputs,
        "target_language_code": "mr-IN",
        "speaker": "shubh",
        "model": "bulbul:v3"
    }
    
    req = urllib.request.Request(TTS_URL, data=json.dumps(data).encode('utf-8'))
    req.add_header('Content-Type', 'application/json')
    req.add_header('api-subscription-key', API_KEY)
    
    try:
        with urllib.request.urlopen(req) as response:
            res_body = response.read().decode('utf-8')
            res_json = json.loads(res_body)
            
            audios = res_json.get('audios', [])
            if not audios:
                print(f"No audios returned for {filename}")
                continue
                
            combined_frames = b''
            params = None
            
            for b64_audio in audios:
                audio_bytes = base64.b64decode(b64_audio)
                with wave.open(io.BytesIO(audio_bytes), 'rb') as w:
                    if params is None:
                        params = w.getparams()
                    combined_frames += w.readframes(w.getnframes())
            
            file_path = f"app/src/main/res/raw/{filename}.wav"
            with wave.open(file_path, 'wb') as w_out:
                w_out.setparams(params)
                w_out.writeframes(combined_frames)
            
            print(f"Saved {file_path}")
    except Exception as e:
        print(f"Error generating {filename}: {e}")
        if hasattr(e, 'read'):
            print(e.read().decode('utf-8'))

